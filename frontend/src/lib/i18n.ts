function lookup(dict: Dict, path: string[]): string | string[] | undefined {
  let node: Dict | string | string[] = dict;
  for (const part of path) {
    if (typeof node === "string" || Array.isArray(node) || node === undefined) return undefined;
    node = node[part];
  }
  return typeof node === "string" || Array.isArray(node) ? node : undefined;
}

/**
 * Résout une clé pointée ("nav.dashboard") dans la langue donnée, avec
 * interpolation `{{param}}` simple. Repli sur le français si la clé manque
 * dans la langue courante (garantit qu'aucun texte ne disparaît juste parce
 * qu'une traduction anglaise n'a pas encore été ajoutée), puis sur la clé
 * brute en tout dernier recours (pour repérer un oubli en développement
 * plutôt que planter silencieusement).
 */
export function translate(
  language: Language,
  key: string,
  params?: Record<string, string | number>
): string {
  const path = key.split(".");
  let value = lookup(dictionaries[language], path);
  if (value === undefined && language !== "fr") {
    value = lookup(dictionaries.fr, path);
  }
  if (value === undefined || Array.isArray(value)) return key;
  if (!params) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (_, name) => String(params[name] ?? ""));
}

/** Variante de translate() pour les clés dont la valeur est une liste (ex.
 * noms de jours de la semaine) plutôt qu'une chaîne unique. */
export function translateList(language: Language, key: string): string[] {
  const path = key.split(".");
  let value = lookup(dictionaries[language], path);
  if (value === undefined && language !== "fr") {
    value = lookup(dictionaries.fr, path);
  }
  return Array.isArray(value) ? value : [];
}
